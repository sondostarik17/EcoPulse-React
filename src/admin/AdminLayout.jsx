import { useEffect, useState } from "react";
import { Link, Outlet, useLocation, useNavigate } from "react-router-dom";
import {
  Bell,
  Menu,
  ShieldCheck,
  LogOut,
  ExternalLink,
  Sun,
  Moon,
  Languages,
  ChevronDown,
  Check,
} from "lucide-react";
import Swal from "sweetalert2";
import Sidebar from "./components/Sidebar";

const pageTitles = {
  "/admin": "Overview",
  "/admin/reports": "Reports Management",
  "/admin/users": "Users Management",
  "/admin/analytics": "Analytics",
  "/admin/settings": "Settings",
};

const languages = [
  { code: "en", label: "English" },
  { code: "ar", label: "العربية" },
  { code: "fr", label: "Français" },
  { code: "es", label: "Español" },
];

export default function AdminLayout() {
  const navigate = useNavigate();
  const location = useLocation();

  const [sidebarOpen, setSidebarOpen] = useState(false);
  const [authorized, setAuthorized] = useState(false);

  const [isDark, setIsDark] = useState(
    () => localStorage.getItem("adminTheme") !== "light"
  );

  const [language, setLanguage] = useState(
    () => localStorage.getItem("selectedLang") || "en"
  );

  const [languageOpen, setLanguageOpen] = useState(false);

  // Check administrator access.
  useEffect(() => {
    const isAdmin =
      localStorage.getItem("isAdminLoggedIn") === "true" &&
      localStorage.getItem("Role") === "admin";

    if (!isAdmin) {
      navigate("/admin/login", { replace: true });
      return;
    }

    setAuthorized(true);
  }, [navigate]);

  // Close mobile menus after navigation.
  useEffect(() => {
    setSidebarOpen(false);
    setLanguageOpen(false);
  }, [location.pathname]);

  // Save and apply the admin theme.
  useEffect(() => {
    localStorage.setItem("adminTheme", isDark ? "dark" : "light");
  }, [isDark]);

  // Set up GTranslate for the admin area.
  useEffect(() => {
    window.gtranslateSettings = {
      default_language: "en",
      languages: languages.map((item) => item.code),
      wrapper_selector: ".gtranslate_wrapper",
    };

    const existingScript = document.querySelector(
      'script[data-ecopulse-admin-gtranslate="true"]'
    );

    if (!existingScript) {
      const script = document.createElement("script");

      script.src =
        "https://cdn.gtranslate.net/widgets/latest/dropdown.js";

      script.async = true;
      script.dataset.ecopulseAdminGtranslate = "true";

      document.body.appendChild(script);
    }

    const syncLanguage = () => {
      setLanguage(localStorage.getItem("selectedLang") || "en");
    };

    window.addEventListener("languageChanged", syncLanguage);

    return () => {
      window.removeEventListener("languageChanged", syncLanguage);
    };
  }, []);

  const changeLanguage = (code) => {
    const select = document.querySelector(
      ".gtranslate_wrapper select, select.gt_selector"
    );

    // Find the target language option generated by the widget.
    const option = select
      ? Array.from(select.options).find((item) => {
          return (
            item.value === code ||
            item.value.endsWith(`|${code}`) ||
            item.value.endsWith(`/${code}`)
          );
        })
      : null;

    if (code === "en" && !select) {
      // English is the widget's default language.
      setLanguage("en");
      localStorage.setItem("selectedLang", "en");
      window.dispatchEvent(new Event("languageChanged"));
      setLanguageOpen(false);
      return;
    }

    if (!select || !option) {
      setLanguageOpen(false);

      Swal.fire({
        icon: "info",
        title: "Translator unavailable",
        text: "The translation widget has not loaded yet. Check your internet connection and refresh the page.",
        confirmButtonColor: "#10b981",
        background: isDark ? "#111412" : "#ffffff",
        color: isDark ? "#ffffff" : "#111827",
      });

      return;
    }

    select.value = option.value;
    select.dispatchEvent(new Event("change", { bubbles: true }));

    setLanguage(code);
    localStorage.setItem("selectedLang", code);
    window.dispatchEvent(new Event("languageChanged"));

    setLanguageOpen(false);
  };

  const logout = async () => {
    const result = await Swal.fire({
      icon: "question",
      title: "Log out of Admin?",
      text: "You will need to sign in again to access the dashboard.",
      showCancelButton: true,
      confirmButtonText: "Log Out",
      cancelButtonText: "Cancel",
      confirmButtonColor: "#dc2626",
      cancelButtonColor: "#4b5563",
      background: isDark ? "#111412" : "#ffffff",
      color: isDark ? "#ffffff" : "#111827",
    });

    if (!result.isConfirmed) return;

    localStorage.setItem("isAdminLoggedIn", "false");
    localStorage.setItem("isLoggedIn", "false");
    localStorage.removeItem("Role");

    window.dispatchEvent(new Event("authChanged"));

    navigate("/admin/login", { replace: true });
  };

  const pageTitle = pageTitles[location.pathname] || "Admin Workspace";

  if (!authorized) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-[#080A09] text-white">
        <div className="text-center">
          <div className="mx-auto flex h-12 w-12 animate-pulse items-center justify-center rounded-2xl bg-emerald-500 text-gray-950">
            <ShieldCheck size={24} />
          </div>

          <p className="mt-4 text-sm text-gray-400">
            Checking admin access...
          </p>
        </div>
      </div>
    );
  }

  return (
    <div
      data-admin-theme={isDark ? "dark" : "light"}
      className={`admin-shell min-h-screen transition-colors duration-300 ${
        isDark
          ? "bg-[#080A09] text-white"
          : "bg-gray-50 text-gray-900"
      }`}
    >
      {/* Styles for light mode across existing admin pages */}
      <style>{`
        [data-admin-theme="light"] {
          background-color: #f4f7f5 !important;
          color: #17221b !important;
          color-scheme: light;
        }

        [data-admin-theme="light"] aside {
          background-color: #ffffff !important;
          border-color: #e2e8e4 !important;
        }

        [data-admin-theme="light"] header {
          background-color: rgba(255,255,255,.94) !important;
          border-color: #e2e8e4 !important;
        }

        [data-admin-theme="light"] [class*="bg-[#080A09]"],
        [data-admin-theme="light"] [class*="bg-[#0B0D0C]"],
        [data-admin-theme="light"] [class*="bg-[#0B0F0D]"],
        [data-admin-theme="light"] [class*="bg-[#0D110F]"],
        [data-admin-theme="light"] [class*="bg-[#0E1712]"],
        [data-admin-theme="light"] [class*="bg-[#101612]"],
        [data-admin-theme="light"] [class*="bg-[#111612]"] {
          background-color: #ffffff !important;
        }

        [data-admin-theme="light"] [class*="bg-gradient-to-br"],
        [data-admin-theme="light"] [class*="from-[#102219]"] {
          background-image: none !important;
          background-color: #ffffff !important;
        }

        [data-admin-theme="light"] [class~="bg-white/[0.02]"],
        [data-admin-theme="light"] [class~="bg-white/[0.025]"],
        [data-admin-theme="light"] [class~="bg-white/[0.03]"],
        [data-admin-theme="light"] [class~="bg-white/[0.04]"] {
          background-color: #f8faf9 !important;
        }

        [data-admin-theme="light"] [class~="text-white"] {
          color: #17221b !important;
        }

        [data-admin-theme="light"] [class~="text-gray-300"] {
          color: #334155 !important;
        }

        [data-admin-theme="light"] [class~="text-gray-400"] {
          color: #475569 !important;
        }

        [data-admin-theme="light"] [class~="text-gray-500"],
        [data-admin-theme="light"] [class~="text-gray-600"] {
          color: #64748b !important;
        }

        [data-admin-theme="light"] [class~="text-emerald-300"] {
          color: #047857 !important;
        }

        [data-admin-theme="light"] [class*="border-white/"],
        [data-admin-theme="light"] [class*="divide-white/"] {
          border-color: #e2e8e4 !important;
        }

        [data-admin-theme="light"] input,
        [data-admin-theme="light"] select,
        [data-admin-theme="light"] textarea {
          background-color: #ffffff !important;
          color: #17221b !important;
          border-color: #d1dbd4 !important;
        }

        [data-admin-theme="light"] input::placeholder {
          color: #94a3b8 !important;
        }

        [data-admin-theme="light"] table thead {
          background-color: #f1f5f2 !important;
        }

        [data-admin-theme="light"] table tbody tr:hover {
          background-color: #f1f8f3 !important;
        }

        [data-admin-theme="light"] .admin-primary-button {
          background-color: #10b981 !important;
          color: #052e20 !important;
        }
      `}</style>

      {/* Translation widget: kept visually hidden for the language menu */}
      <div
        className="gtranslate_wrapper"
        aria-hidden="true"
        style={{
          position: "absolute",
          width: "1px",
          height: "1px",
          overflow: "hidden",
          clipPath: "inset(50%)",
          whiteSpace: "nowrap",
        }}
      />

      <div className="flex min-h-screen">
        <Sidebar
          open={sidebarOpen}
          onClose={() => setSidebarOpen(false)}
        />

        <div className="min-w-0 flex-1">
          {/* Topbar */}
          <header className="sticky top-0 z-30 flex min-h-[82px] items-center justify-between gap-3 border-b border-white/[0.07] bg-[#080A09]/90 px-3 backdrop-blur-xl sm:px-5 lg:px-8">
            <div className="flex min-w-0 items-center gap-3">
              <button
                type="button"
                onClick={() => setSidebarOpen(true)}
                aria-label="Open sidebar"
                className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl border border-white/10 bg-white/[0.03] text-gray-400 transition hover:bg-white/[0.07] lg:hidden"
              >
                <Menu size={20} />
              </button>

              <div className="min-w-0">
                <p className="text-xs font-medium text-gray-500">
                  EcoPulse / Admin
                </p>

                <h1 className="mt-1 truncate text-base font-extrabold tracking-tight sm:text-xl">
                  {pageTitle}
                </h1>
              </div>
            </div>

            {/* Topbar actions */}
            <div className="flex shrink-0 items-center gap-1.5 sm:gap-2.5">
              {/* View Website */}
              <Link
                to="/"
                title="Open the user website"
                className="inline-flex h-10 items-center justify-center gap-2 rounded-xl border border-emerald-500/20 bg-emerald-500/10 px-2.5 text-xs font-bold text-emerald-600 transition hover:bg-emerald-500/20 dark:text-emerald-300 sm:px-3.5 sm:text-sm"
              >
                <ExternalLink size={16} />
                <span className="hidden md:inline">View Website</span>
                <span className="md:hidden">Website</span>
              </Link>

              {/* Language selector */}
              <div className="relative">
                <button
                  type="button"
                  onClick={() => setLanguageOpen((previous) => !previous)}
                  aria-label="Change language"
                  aria-expanded={languageOpen}
                  title="Change language"
                  className="flex h-10 items-center justify-center gap-1.5 rounded-xl border border-white/10 bg-white/[0.03] px-2.5 text-gray-400 transition hover:border-emerald-500/30 hover:text-emerald-500 sm:px-3"
                >
                  <Languages size={18} />
                  <span className="text-xs font-bold uppercase">
                    {language === "zh-CN"
                      ? "ZH"
                      : language}
                  </span>
                  <ChevronDown size={13} />
                </button>

                {languageOpen && (
                  <>
                    <button
                      type="button"
                      aria-label="Close language menu"
                      className="fixed inset-0 z-40 cursor-default"
                      onClick={() => setLanguageOpen(false)}
                    />

                    <div className="absolute right-0 top-[calc(100%+10px)] z-50 w-44 overflow-hidden rounded-xl border border-gray-200 bg-white p-1.5 shadow-2xl dark:border-white/10 dark:bg-[#111612]">
                      <p className="px-3 py-2 text-[10px] font-bold uppercase tracking-wider text-gray-500">
                        Select language
                      </p>

                      {languages.map((item) => (
                        <button
                          key={item.code}
                          type="button"
                          onClick={() => changeLanguage(item.code)}
                          className="flex w-full items-center justify-between gap-2 rounded-lg px-3 py-2.5 text-left text-sm font-medium text-gray-700 transition hover:bg-emerald-50 hover:text-emerald-700 dark:text-gray-300 dark:hover:bg-emerald-500/10 dark:hover:text-emerald-300"
                        >
                          <span>{item.label}</span>
                          {language === item.code && (
                            <Check size={15} className="text-emerald-500" />
                          )}
                        </button>
                      ))}
                    </div>
                  </>
                )}
              </div>

              {/* Dark / Light mode */}
              <button
                type="button"
                onClick={() => setIsDark((previous) => !previous)}
                aria-label={isDark ? "Switch to light mode" : "Switch to dark mode"}
                title={isDark ? "Light mode" : "Dark mode"}
                className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl border border-white/10 bg-white/[0.03] text-gray-400 transition hover:border-amber-400/30 hover:text-amber-400"
              >
                {isDark ? (
                  <Sun size={19} className="text-amber-400" />
                ) : (
                  <Moon size={19} className="text-emerald-600" />
                )}
              </button>

              {/* Notifications */}
              <div
                title="Admin notifications"
                className="hidden h-10 w-10 items-center justify-center rounded-xl border border-white/[0.08] bg-white/[0.025] text-gray-400 sm:flex"
              >
                <Bell size={18} />
              </div>

              {/* Administrator */}
              <div className="hidden items-center gap-2 md:flex">
                <div className="flex h-9 w-9 items-center justify-center rounded-full border border-emerald-400/20 bg-emerald-400/10 text-emerald-500">
                  <ShieldCheck size={18} />
                </div>

                <div>
                  <p className="text-xs font-bold">Administrator</p>
                  <p className="mt-0.5 text-[10px] text-emerald-500">
                    Admin session
                  </p>
                </div>
              </div>

              {/* Logout */}
              <button
                type="button"
                onClick={logout}
                title="Log out"
                className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl border border-red-500/15 bg-red-500/[0.06] text-red-500 transition hover:bg-red-500/15 sm:w-auto sm:gap-2 sm:px-3"
              >
                <LogOut size={17} />
                <span className="hidden text-xs font-bold sm:inline">
                  Logout
                </span>
              </button>
            </div>
          </header>

          {/* Current admin page */}
          <main className="min-w-0 p-4 sm:p-6 lg:p-8">
            <Outlet />
          </main>

          <footer className="flex flex-wrap items-center justify-between gap-2 border-t border-white/[0.06] px-4 py-5 text-xs text-gray-500 sm:px-6 lg:px-8">
            <p>© {new Date().getFullYear()} EcoPulse Admin</p>
            <p>Cleaner communities start here.</p>
          </footer>
        </div>
      </div>
    </div>
  );
}